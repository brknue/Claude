#!/usr/bin/env node
// plain — checks plain/projects.js and regenerates plain/files.js (file lists used for "Download all files").
// Run from anywhere:  node plain/build.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(readFileSync(join(root, 'plain/projects.js'), 'utf8'), ctx);
vm.runInNewContext(readFileSync(join(root, 'plain/i18n.js'), 'utf8'), ctx);
const projects = ctx.window.PLAIN_PROJECTS, i18n = ctx.window.PLAIN_I18N;

const SKIP = new Set(['.git', 'node_modules', '.DS_Store', '.env', '.netlify', '.vercel']);
const TAGS = ['science', 'language', 'learning', 'tools', 'health', 'explore'];
const NOTES = ['apikey', 'server', 'external', 'webgpu', 'german', 'lookup'];
const errors = [], warnings = [];

function walk(dir, out) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.env')) continue;
    const p = join(dir, name), s = statSync(p);
    if (s.isDirectory()) walk(p, out); else out.push({ path: relative(root, p).split(sep).join('/'), bytes: s.size });
  }
  return out;
}

const ids = new Set(), files = {};
for (const p of projects) {
  const where = `project "${p.id}"`;
  if (!p.id || !/^[a-z0-9][a-z0-9-]*$/.test(p.id)) errors.push(`${where}: id must be a lowercase folder name`);
  if (ids.has(p.id)) errors.push(`${where}: duplicate id`); ids.add(p.id);
  if (!existsSync(join(root, p.id))) { errors.push(`${where}: folder ${p.id}/ does not exist`); continue; }
  if (!p.name) errors.push(`${where}: missing name`);
  if (!p.entry || !existsSync(join(root, p.entry))) errors.push(`${where}: entry file "${p.entry}" not found`);
  if (p.open && !/^https:\/\//.test(p.open)) {
    const target = join(root, p.open, p.open.endsWith('/') ? 'index.html' : '');
    if (!existsSync(target)) errors.push(`${where}: open path "${p.open}" has no file at ${relative(root, target)}`);
  }
  if (!p.desc || !p.desc.en) errors.push(`${where}: desc.en is required`);
  for (const l of Object.keys(i18n)) if (!p.desc || !p.desc[l]) warnings.push(`${where}: no "${l}" description (English is shown)`);
  for (const g of p.tags || []) if (!TAGS.includes(g)) errors.push(`${where}: unknown tag "${g}" (use ${TAGS.join(', ')})`);
  for (const n of p.notes || []) if (!NOTES.includes(n)) errors.push(`${where}: unknown note "${n}" (use ${NOTES.join(', ')})`);
  const list = walk(join(root, p.id), []);
  files[p.id] = { files: list.map(f => f.path), bytes: list.reduce((s, f) => s + f.bytes, 0) };
}
for (const l of Object.keys(i18n)) for (const k of Object.keys(i18n.en)) if (!(k in i18n[l])) warnings.push(`i18n "${l}": missing "${k}"`);

const out = '/* Generated by plain/build.mjs — do not edit by hand. */\nwindow.PLAIN_FILES = ' + JSON.stringify(files, null, 1) + ';\n';
writeFileSync(join(root, 'plain/files.js'), out);
for (const w of warnings) console.log('warning:', w);
if (errors.length) { for (const e of errors) console.error('ERROR:', e); process.exit(1); }
console.log(`ok: ${projects.length} projects, ${Object.values(files).reduce((s, f) => s + f.files.length, 0)} files listed in plain/files.js`);
